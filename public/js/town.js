/* 마을 — **손으로 만든 지도다.** 던전 생성기를 쓰지 않는다.
 *
 * 마을은 매번 같아야 한다. 돌아올 때마다 포탈이 다른 자리에 있으면 집이 아니라
 * 또 하나의 던전이다. 같은 자리에 같은 것이 있는 것 자체가 **쉼**이다.
 *
 * ⚠ 마을에는 몬스터가 없다. "안전한 곳" 이 실제로 안전해야 그 밖이 무서워진다.
 * ⚠ 지도를 글자로 적는다. 좌표로 적으면 고칠 때 머릿속에 그림을 그려야 한다 —
 *   글자면 눈으로 보고 고친다(벽 하나 옮기는 데 5분이 걸리지 않는다).
 */
(function (global) {
  "use strict";

  var D = global.DUNGEON;

  /* # 벽 · . 바닥 · P 포탈 · W 샘 · @ 시작 자리
   * ⚠ 줄 길이가 모두 같아야 한다 — 아래 buildTown 이 검사한다. */
  var MAP = [
    "##########################",
    "#........................#",
    "#........................#",
    "#...###............###...#",
    "#...###............###...#",
    "#...###............###...#",
    "#........................#",
    "#.......P........W.......#",
    "#........................#",
    "#........................#",
    "#...........@............#",
    "#........................#",
    "#...###............###...#",
    "#...###............###...#",
    "#...###............###...#",
    "#........................#",
    "#........................#",
    "##########################"
  ];

  /* 말을 거는 것들. **한 곳에 모은다** — 화면·조작·규칙이 전부 이 목록을 본다.
   * 세 곳에 나눠 적으면 반드시 하나가 어긋난다(포탈은 눌리는데 글자가 안 뜨는 식). */
  var PROPS = {
    P: { id: "portal", sprite: "t_portal", label: "심연의 문", verb: "들어간다",
         reach: 1.4 },
    W: { id: "well",   sprite: "t_well",   label: "회복의 샘", verb: "마신다",
         reach: 1.4 }
  };

  function buildTown() {
    var h = MAP.length, w = MAP[0].length;
    for (var i = 0; i < h; i++) {
      if (MAP[i].length !== w)
        throw new Error("마을 지도 " + (i + 1) + "줄의 길이가 다르다: " +
                        MAP[i].length + " ≠ " + w);
    }
    var lv = new D.Level(w, h);
    var props = [], start = null;
    for (var y = 0; y < h; y++) {
      for (var x = 0; x < w; x++) {
        var c = MAP[y][x];
        var id = y * w + x;
        lv.tiles[id] = (c === "#") ? D.WALL : D.FLOOR;
        if (c === "@") start = { x: x + 0.5, y: y + 0.5 };
        var p = PROPS[c];
        if (p) props.push({ id: p.id, x: x + 0.5, y: y + 0.5, def: p });
      }
    }
    /* 마을은 **전부 보인다.** 안개를 씌우면 집 안에서 길을 잃는다. */
    lv.visible.fill(1);
    lv.seen.fill(1);
    lv.rooms = [{ x: 1, y: 1, w: w - 2, h: h - 2 }];
    lv.upAt = start ? { x: Math.floor(start.x), y: Math.floor(start.y) } : { x: 2, y: 2 };
    return { level: lv, props: props, start: start || { x: 2.5, y: 2.5 } };
  }

  global.TOWN = { MAP: MAP, PROPS: PROPS, build: buildTown };
})(window);
